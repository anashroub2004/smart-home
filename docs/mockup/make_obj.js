// Export the mockup (docs/mockup/mockup-design.html) as a 3D file for Blender / SketchUp / Fusion / Onshape:
//   node docs/mockup/make_obj.js      ->  docs/mockup/mockup.obj + mockup.mtl
// The data (rooms, walls, furniture, parts, hub) is read from the page itself, so the page and the file never disagree.
// Units: centimetres, scale 1:10. Axes like three.js / glTF: X = east, Y = up, -Z = north (plan y).
// Furniture and parts are boxes of their real size (the detailed shapes are for the 3D program); wires are thin
// square tubes along the same route the page draws: down the part's hole, under the raised floor, out of the east wall
// to the node's ESP32 in the hub box.
const fs = require("fs");
const path = require("path");

const page = fs.readFileSync(path.join(__dirname, "mockup-design.html"), "utf8");
const start = page.indexOf("const W = ");
const end = page.indexOf("const css = ");
if (start < 0 || end < 0) throw new Error("data block not found in mockup-design.html");
const M = new Function(page.slice(start, end) + "\nreturn { W, D, H, T, ROOMS, WALLS, FURN, COMP, HUB, NODE_LABEL };")();
const { W, D, H, T, ROOMS, WALLS, FURN, COMP, HUB } = M;

let obj = "# Smart home mockup — generated by docs/mockup/make_obj.js from mockup-design.html\n# units: cm (scale 1:10), Y up, X east, -Z north\nmtllib mockup.mtl\n";
let v = 0;                                   // vertices written so far (OBJ indices are 1-based and global)
const name = s => s.replace(/[^A-Za-z0-9_]+/g, "_").replace(/_+$/, "");

// a box from its lower south-west corner (plan x, y, z) and size (w east, d north, h up)
function box(o, material, x, y, z, w, d, h) {
  if (w <= 0 || d <= 0 || h <= 0) return;
  obj += `o ${name(o)}\nusemtl ${material}\n`;
  const P = [[x, y, z], [x + w, y, z], [x + w, y + d, z], [x, y + d, z],
             [x, y, z + h], [x + w, y, z + h], [x + w, y + d, z + h], [x, y + d, z + h]];
  for (const [px, py, pz] of P) obj += `v ${px.toFixed(3)} ${pz.toFixed(3)} ${(-py).toFixed(3)}\n`;
  const f = [[1, 2, 6, 5], [2, 3, 7, 6], [3, 4, 8, 7], [4, 1, 5, 8], [5, 6, 7, 8], [4, 3, 2, 1]];
  for (const q of f) obj += "f " + q.map(i => i + v).join(" ") + "\n";
  v += 8;
}
// a thin tube (square, 0.3 cm) from point a to point b, axis-aligned segments only
function segment(o, material, a, b, r = 0.15) {
  const lo = a.map((c, i) => Math.min(c, b[i]) - r), hi = a.map((c, i) => Math.max(c, b[i]) + r);
  box(o, material, lo[0], lo[1], lo[2], hi[0] - lo[0], hi[1] - lo[1], hi[2] - lo[2]);
}

// ---- floors, walls (with door / window openings), glass
box("Base_board", "base", -1, -1, -3.5, W + 2, D + 2, 0.5);
box("Raised_floor", "floor", -1, -1, -0.5, W + 2, D + 2, 0.5);
WALLS.forEach((w, n) => {
  const horiz = w.a[1] === w.b[1], s0 = horiz ? w.a[0] : w.a[1], s1 = horiz ? w.b[0] : w.b[1];
  const piece = (p, q, z0, z1, tag) => horiz
    ? box(`Wall_${n}_${tag}`, "wall", p, w.a[1] - T / 2, z0, q - p, T, z1 - z0)
    : box(`Wall_${n}_${tag}`, "wall", w.a[0] - T / 2, p, z0, T, q - p, z1 - z0);
  let pos = s0, k = 0;
  for (const op of w.open.slice().sort((a, b) => a[0] - b[0])) {
    piece(pos, op[0], 0, H, `part${k++}`);
    piece(op[0], op[1], 0, op[2], `sill${k}`);
    piece(op[0], op[1], op[3], H, `lintel${k}`);
    if (op[4] === "window") horiz
      ? box(`Window_${n}_${k}`, "glass", op[0], w.a[1] - 0.1, op[2], op[1] - op[0], 0.2, op[3] - op[2])
      : box(`Window_${n}_${k}`, "glass", w.a[0] - 0.1, op[0], op[2], 0.2, op[1] - op[0], op[3] - op[2]);
    pos = op[1];
  }
  piece(pos, s1, 0, H, `part${k}`);
});
for (const [bx, by, bw] of [[0, 16.2, 50], [50, 16.2, 30], [0, 46.2, 56], [56, 46.2, 24]]) box(`Ceiling_beam_${bx}_${by}`, "wall", bx, by, H - 0.6, bw, 1.6, 0.6);

// ---- furniture (boxes of the real footprint and height)
FURN.forEach((f, i) => box(`Furniture_${f.r}_${f.n}_${i}`, "furniture", f.x, f.y, 0, f.w, f.d, f.h));

// ---- hub box + cable exit
box("Hub_base", "hub", HUB.x, HUB.y, -3.5, HUB.w, HUB.d, 0.4);
box("Hub_box_acrylic", "glass", HUB.x, HUB.y, -3.1, HUB.w, HUB.d, HUB.h);
box("Cable_exit_east_wall", "hub", 80, 30.4, -2.6, HUB.x - 80, 2.2, 2);

// ---- parts (2.4 cm cubes at their mount point; hub parts lie on the hub floor)
for (const k of COMP) {
  const z = k.r === "hub" ? -2.7 : Math.min(k.z, H - 1);
  const mat = k.st === "planned" ? `${k.node}_planned` : k.node;
  if (k.r === "hub") box(`Part_${k.id}_${k.p}`, mat, k.x - 4, k.y - 3, z, 8, 6, 2);
  else box(`Part_${k.id}_${k.p}`, mat, k.x - 1.2, k.y - 1.2, z - 1.2, 2.4, 2.4, 2.4);
}

// ---- wires: the same route as the page (down the hole, under the floor, east exit, to the node's ESP32)
const FLOOR_Z = -1.6;
let lane = 0;
for (const k of COMP) {
  if (k.r === "hub") continue;
  const L = lane++ % 9, pts = [];
  let x = k.x, y = k.y; const z = Math.min(k.z, H - 1);
  pts.push([x, y, z]);
  if (k.z >= 20) {                         // ceiling light: along the beam to the nearest wall
    const room = ROOMS.find(r => r.id === k.r) || ROOMS[0];
    const cand = [[room.x + 0.6, y], [room.x + room.w - 0.6, y], [x, room.y + 0.6], [x, room.y + room.d - 0.6]];
    [x, y] = cand.sort((a, b) => Math.hypot(a[0] - k.x, a[1] - k.y) - Math.hypot(b[0] - k.x, b[1] - k.y))[0];
    pts.push([x, y, z]);
  }
  const trunkY = (k.y > 34 ? 37 : 30.5) + L * 0.22, exitY = 31 + L * 0.12, ex = 78.5 - L * 0.1;
  pts.push([x, y, FLOOR_Z], [x, trunkY, FLOOR_Z], [ex, trunkY, FLOOR_Z], [ex, exitY, FLOOR_Z], [HUB.x + 1, exitY, FLOOR_Z]);
  const esp = COMP.find(c => c.r === "hub" && c.node === k.node && c.p.toLowerCase().includes("esp32"));
  if (esp) pts.push([esp.x, exitY, FLOOR_Z], [esp.x, esp.y + 3, FLOOR_Z]);
  const mat = k.st === "planned" ? `${k.node}_planned` : k.node;
  for (let i = 1; i < pts.length; i++) segment(`Wire_${k.id}_${k.p}_${i}`, mat, pts[i - 1], pts[i]);
}

const mtl = `# materials for mockup.obj
newmtl base\nKd 0.75 0.78 0.84\nnewmtl floor\nKd 0.93 0.94 0.96
newmtl wall\nKd 0.88 0.90 0.94
newmtl glass\nKd 0.62 0.83 0.94\nd 0.35
newmtl furniture\nKd 0.73 0.56 0.40
newmtl living\nKd 0.06 0.55 0.55
newmtl bedroom\nKd 0.77 0.48 0.07
newmtl door\nKd 0.76 0.25 0.23
newmtl hub\nKd 0.42 0.31 0.73
newmtl living_planned\nKd 0.06 0.55 0.55\nd 0.5
newmtl bedroom_planned\nKd 0.77 0.48 0.07\nd 0.5
newmtl door_planned\nKd 0.76 0.25 0.23\nd 0.5
newmtl hub_planned\nKd 0.42 0.31 0.73\nd 0.5
`;
fs.writeFileSync(path.join(__dirname, "mockup.obj"), obj);
fs.writeFileSync(path.join(__dirname, "mockup.mtl"), mtl);
console.log(`mockup.obj: ${v} vertices, ${(obj.match(/^o /gm) || []).length} objects`);
